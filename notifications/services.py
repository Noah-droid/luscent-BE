import resend
import logging
from django.conf import settings

logger = logging.getLogger(__name__)

# Initialize Resend
if settings.RESEND_API_KEY:
    resend.api_key = settings.RESEND_API_KEY



def send_verification_email(user, otp):
    """
    Sends a verification OTP to the user.
    """
    if not settings.RESEND_API_KEY:
        logger.warning("Resend API key not configured. Skipping email.")
        return

    try:
        html_content = f"""
        <div style="font-family: sans-serif; max-width: 600px; margin: 0 auto;">
            <h2>Verify your Email</h2>
            <p>Hello {user.username},</p>
            <p>Your Luscent verification code is:</p>
            
            <div style="text-align: center; margin: 30px 0;">
                <span style="background-color: #f3f4f6; padding: 12px 24px; font-size: 24px; letter-spacing: 5px; font-weight: bold; border-radius: 4px;">{otp}</span>
            </div>
            
            <p style="color: #666; font-size: 14px;">This code will expire shortly.</p>
        </div>
        """

        params = {
            "from": settings.DEFAULT_FROM_EMAIL,
            "to": [user.email],
            "subject": "Your Verification Code",
            "html": html_content,
        }

        resend.Emails.send(params)
        logger.info(f"OTP sent to {user.email}")
        
    except Exception as e:
        logger.error(f"Failed to send verification email: {e}")



